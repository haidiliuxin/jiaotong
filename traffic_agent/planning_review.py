"""Deterministic evidence coverage and caveats alongside model prose.

These checks do not certify every sentence generated by a language model.
They expose what was actually tested, independent of the model's confidence.
"""
import re

PREVIOUS_GATE_VERSION = 'parking-completion-v2'
GATE_VERSION = 'parking-completion-v3'


def strength_requested(request):
    text=re.sub(r'不(?:用|必|要)?(?:比较|对比).{0,8}(?:强度|等级)', '', request)
    return bool(re.search(r'(?:比较|对比|检验|评估).{0,18}(?:强度|等级)|(?:强度|等级).{0,12}(?:比较|对比)|(?:1|一)级.{0,8}(?:2|二)级|(?:2|二)级.{0,8}(?:1|一)级',text))


def required_policies(task):
    from .spatial_requirements import task_regions
    spatial=(2 if strength_requested(task.get('request','')) else 1)*task_regions(task)
    return max(spatial,task.get('comparison_policies') or 1)


def measured_policies(state):
    """Count distinct parking treatments completed at every frozen demand."""
    factors=set(state['task'].get('demand_factors',[1]))
    by_policy={}
    for run in state.get('runs',[]):
        if (run.get('changes') and run.get('execution',{}).get('status')=='completed'
                and any('parking' in change for change in run['changes'])):
            key=tuple(sorted((change['from_node'],change['to_node'],change['parking'])
                             for change in run['changes'] if 'parking' in change))
            by_policy.setdefault(key,set()).add(run.get('demand_factor'))
    return sum(factors<=tested for tested in by_policy.values())


def minimum_model_requests(tasks):
    """Legacy worst-order bound; current scheduling uses planning_budget."""
    parking=sum(t['scenario']=='parking' for t in tasks)
    return sum(required_policies(t)+1 if t['scenario']=='parking' else 2 if t['scenario']=='oneway' else 1 for t in tasks)+min(parking,max(0,len(tasks)-1))


def footprint(changes):
    return tuple(sorted((c['from_node'],c['to_node']) for c in changes if 'parking' in c))


def coverage(state):
    if state.get('task',{}).get('scenario') != 'parking':
        return None
    task=state['task']
    policies=[r for r in state.get('runs',[]) if r.get('changes') and r.get('execution',{}).get('status')=='completed']
    levels=set()
    footprints={}
    for r in policies:
        changes=[c for c in r['changes'] if 'parking' in c]
        if not changes:continue
        found={c['parking'] for c in changes}
        levels.update(found)
        key=(r['demand_factor'],tuple(sorted((c['from_node'],c['to_node']) for c in changes)))
        if len(found)==1:footprints.setdefault(key,set()).update(found)
    factors=task.get('demand_factors',[1])
    anchor=footprint(policies[0]['changes']) if policies else ()
    strict=state.get('planning_protocol') in ('observed-planning-v2','observed-planning-v3')
    compared=(bool(anchor) and all({1,2}<=footprints.get((f,anchor),set()) for f in factors)) if strict else any({1,2}<=v for v in footprints.values())
    needed=strength_requested(task.get('request',''))
    comparison_target=task.get('comparison_policies') or 0
    compared_policies=measured_policies(state) if comparison_target else 0
    spatial=None
    if state.get('planning_protocol')=='observed-planning-v3':
        from .spatial_requirements import task_regions,progress
        if task_regions(task)>1:
            spatial=progress(state,needed)
            if needed:compared=len(spatial['completed'])>=spatial['required']
    missing=[]
    if needed and not compared:missing.append('尚未在全部约定需求、相同治理方向下比较停车1级与2级，不能判断哪个强度更合适。')
    checks=[]
    if strict:
        completed=[r for r in state.get('runs',[]) if r.get('execution',{}).get('status')=='completed']
        baselines={r['demand_factor']:r for r in completed if not r['changes']}
        policy_complete=any(all(any(p['demand_factor']==f and p['changes']==r['changes'] for p in policies) for f in factors) for r in policies)
        checks=[dict(id='baseline',label='各需求的新基准',fulfilled=all(f in baselines for f in factors)),
                dict(id='policy',label='治理候选的实际执行与配对',fulfilled=policy_complete)]
        if needed:checks.append(dict(id='strength',label='同方向停车1级 / 2级完整对照',fulfilled=compared))
        if comparison_target:checks.append(dict(id='alternatives',label=f'至少{comparison_target}个不同停车方案的完整同需求配对',fulfilled=compared_policies>=comparison_target))
        if spatial:checks.append(dict(id='regions',label=f"至少{spatial['required']}个不同候选区完成配对实测",fulfilled=len(spatial['completed'])>=spatial['required']))
        if task.get('repeat_baseline'):checks.append(dict(id='repeat',label='同输入复跑一致性',fulfilled=state.get('repeatability',{}).get('exact_match') is True and any(r.get('name')=='baseline_repeat' and not r['changes'] and r['demand_factor']==1 for r in completed)))
        execution_complete=all(c['fulfilled'] for c in checks)
        refs=[f"{state['id']}:{r['name']}" for r in completed if r.get('metrics')]
        from .study_handoff import closes_study
        reviewed=any(t.get('status')=='accepted' and closes_study(t.get('action'),t.get('input',{}).get('context',{}))
                     and t.get('input',{}).get('evidence_refs')==refs for t in state.get('planner_trace',[]))
        checks.append(dict(id='review',label='模型读取完整结果并完成复核',fulfilled=bool(refs) and reviewed))
        if state.get('conclusion_protocol'):
            from .conclusion_review import assess_traces
            checked=assess_traces(state.get('planner_trace',[]))
            checks.append(dict(id='conclusion',label='实测代价确认与已知证据缺口核对',
                               fulfilled=reviewed and checked['status']=='no_detected_conflict'))
        missing=[c['label']+'尚未完成。' for c in checks if not c['fulfilled']]
    else:
        execution_complete=not missing
    matrix=[]
    anchors=[(None,anchor)]
    if spatial:anchors=[(area,footprint(run['changes'])) for area,run in list(spatial['anchors'].items())[:spatial['required']]]
    if needed and anchor:
        for area,directions in anchors:
            for factor in factors:
                cells=[]
                for level in (1,2):
                    r=next((r for r in policies if r['demand_factor']==factor and footprint(r['changes'])==directions and {c['parking'] for c in r['changes']}=={level}),None)
                    cells.append(dict(level=level,run=r.get('name') if r else None,
                                      speed_kmh=r.get('metrics',{}).get('core',{}).get('weighted_speed_kmh') if r else None,
                                      comparison=r.get('comparison') if r else None))
                    if r and state.get('regions'):
                        from .data import metrics
                        cells[-1]['speed_kmh']=metrics([road for road in r.get('core_rows',[]) if (road['from_node'],road['to_node']) in directions])['weighted_speed_kmh']
                matrix.append(dict(demand_factor=factor,levels=cells))
                if state.get('regions'):matrix[-1]['speed_scope']='treated'
                if area:matrix[-1].update(region=area,region_title=next(r['title'] for r in state['regions'] if r['id']==area))
    if comparison_target and compared_policies<comparison_target and not strict:
        missing.append(f'尚未测齐{comparison_target}个不同停车方案的全部约定需求。')
    return dict(strength_comparison_requested=needed, strength_compared=compared, requirements=checks,
                comparison_directions=[list(p) for p in anchor], strength_matrix=matrix, execution_complete=execution_complete,
                measured_levels=sorted(levels), unanswered=missing, complete=not missing,
                remaining_native_runs=max(0,task['max_runs']-state.get('run_count',0)) if 'max_runs' in task else None)


def parking_gate(state, options, available, cost, model_remaining, *, version=GATE_VERSION):
    """Keep only actions that leave enough budget to finish the mandatory study.

    The first measured footprint anchors the strength comparison. More actions
    can be explored after this pair, but cannot replace its missing counterpart.
    """
    if version not in (None,PREVIOUS_GATE_VERSION,GATE_VERSION):
        raise ValueError('停车完成门槛协议不符')
    task=state['task']
    policies=[r for r in state.get('runs',[]) if r.get('changes') and r.get('execution',{}).get('status')=='completed']
    review=coverage(state)
    remaining=(0 if policies else 1)
    needed=strength_requested(task.get('request',''))
    if needed:remaining=0 if review['strength_compared'] else (1 if policies else 2)
    permitted=dict(options)
    if needed and remaining==1:
        anchor=policies[0]['changes']
        opposite=3-anchor[0]['parking']
        permitted={k:v for k,v in permitted.items() if footprint(v['changes'])==footprint(anchor) and {c['parking'] for c in v['changes']}=={opposite}}
    if state.get('planning_protocol')=='observed-planning-v3':
        from .spatial_requirements import task_regions,restrict
        if task_regions(task)>1:
            permitted,spatial=restrict(options,state,needed)
            remaining=spatial['remaining']
    comparison_target=(task.get('comparison_policies') or 0) if version==GATE_VERSION else 0
    compared_policies=measured_policies(state) if comparison_target else 0
    if comparison_target:
        remaining=max(remaining,comparison_target-compared_policies)
    affordable=(available>=remaining*cost and model_remaining>=remaining+1)
    if not affordable or model_remaining<2:permitted={}
    guard=dict(required_policy_decisions=remaining, required_native_runs=remaining*cost,
               required_model_requests=remaining+1, stop_allowed=remaining==0,
               can_finish=affordable and (bool(permitted) or remaining==0),
               reason=('必需实测已齐，可复核结束；进一步搜索由模型判断。' if remaining==0 else
                       '完成明确的研究目标前不能停止；预留同方向对照和最终复核预算。'))
    if version in (PREVIOUS_GATE_VERSION,GATE_VERSION):
        guard.update(version=GATE_VERSION,strength_comparison_required=needed)
        if version==PREVIOUS_GATE_VERSION:guard['version']=PREVIOUS_GATE_VERSION
        if version==GATE_VERSION:
            guard.update(required_candidate_comparisons=comparison_target,measured_candidate_comparisons=compared_policies)
        if remaining:
            guard['reason']=(f'尚需完成{remaining}项停车候选及其约定需求配对，再复核结果。'+
                             ('本任务要求同方向1/2级完整强度对照。' if needed else '本任务未要求1/2级强度对照。')+
                             (f'另须实测至少{comparison_target}个不同停车方案。' if comparison_target else ''))
    return permitted,guard


def finish_research(agent):
    review=coverage(agent.state)
    agent.state['goal_review']=review
    agent.state['status']='completed' if review['complete'] else 'incomplete'
    if not review['complete']:
        agent.state['reason']='研究未完成：'+' '.join(review['unanswered'])
    if agent.state.get('evidence_protocol'):
        from .research_evidence import latest_review
        agent.state['research_review']=latest_review(agent.state)
    agent.event('completion_check',review)


def decision_notes(entry):
    """Derive notices for old and new evidence without changing saved history."""
    context=entry.get('input',{}).get('context',{})
    options={k:v for k,v in entry.get('input',{}).get('allowed_actions',{}).items() if k!='stop'}
    notes=[]
    if entry.get('action')=='stop' and options and entry.get('version') not in ('observed-planning-v2','observed-planning-v3'):
        available=context.get('available_policy_runs')
        cost=context.get('policy_cost',1)
        if available is not None:
            notes.append(f'执行器核对：仍有{available}次候选仿真预算；一项未测候选需要{cost}次。此次停止是模型选择，并非预算耗尽。')
        else:
            notes.append(f'执行器核对：仍有{len(options)}组研究可选，本次由模型选择提前停止。')
        notes.append('未测试的方案不能断言必然更差；只可比较已经完成的同条件结果。')
    prose=' '.join(str(entry.get(k,'')) for k in ('summary','reason','risk','next_check'))
    if re.search(r'停车\s*0\s*级',prose) or (entry.get('kind')=='parking' and re.search(r'(?<!\d)0\s*级',prose)):
        notes.append('能力核对：当前停车工具只开放1/2级；文字提到的停车0级不在可执行目录内。')
    if entry.get('action')=='stop' and re.search(r'最优|最好|最佳',prose):
        notes.append('结论范围：仅比较本次实际测试的合法候选及需求条件，不能把“最优”外推到未测道路、需求或措施。')
    if context.get('goal_review',{}).get('unanswered') and entry.get('version') not in ('observed-planning-v2','observed-planning-v3'):
        notes.extend(context['goal_review']['unanswered'])
    from .conclusion_review import assess_entry
    if entry.get('status') in ('accepted','rejected'):
        notes.extend(i['message'] for i in assess_entry(entry)['issues'])
    return list(dict.fromkeys(notes))


def display_trace(traces):
    from .conclusion_review import assess_entry
    from .choice_rationale import text as choice_reason
    from .risk_review import display as risk_display
    from .candidate_comparison import selected as selected_comparison
    return [dict(t,verification_notes=decision_notes(t),
                 stop_basis=public_stop_basis(t),
                 **(dict(selection_reason=choice_reason(t)) if choice_reason(t) else {}),
                 **(dict(risk_review=risk_display(t)) if risk_display(t) else {}),
                 **(dict(candidate_comparison=selected_comparison(t)) if selected_comparison(t) else {}),
                 **(dict(stop_basis_origin='completed-study-comparisons') if programme_stop_basis(t) else {}),
                 **({'conclusion_review':assess_entry(t)} if t.get('status') in ('accepted','rejected') else {})) for t in traces]


def public_stop_basis(entry):
    """Explain an accepted stop using frozen completion facts, not model prose."""
    if entry.get('status') != 'accepted' or entry.get('action') != 'stop':
        return None
    programme=programme_stop_basis(entry)
    if programme:return programme
    guard = entry.get('input', {}).get('context', {}).get('completion_guard')
    if not isinstance(guard, dict) or guard.get('stop_allowed') is not True:
        return None
    required = guard.get('required_candidate_comparisons')
    measured = guard.get('measured_candidate_comparisons')
    if type(required) is int and required > 1 and type(measured) is int and measured >= required:
        basis = f'本组要求至少实测{required}个不同治理候选，已完成{measured}个'
        if guard.get('strength_comparison_required') is False:
            basis += '；原问题未要求同方向停车等级对照，未测等级不算已验证'
        return basis + '。'
    return '本组必需实测已齐，模型决定停止新增试验。'


def programme_stop_basis(entry):
    """Use each group's actual measured coverage, without replacing model text."""
    if entry.get('status')!='accepted' or entry.get('action')!='stop':return None
    context=entry.get('input',{}).get('context',{})
    groups=context.get('programme_evidence',{}).get('groups',[])
    comparisons=context.get('programme_comparisons',[])
    from .study_comparison import VERSION,coverage_text
    if (not groups or not all(g.get('execution_complete') is True for g in groups)
            or len(comparisons)!=len(groups) or any(g.get('version')!=VERSION for g in comparisons)
            or {g.get('study_id') for g in comparisons}!={g['id'] for g in groups}):return None
    return '按本次完成记录：'+ '；'.join(g['title']+'（'+coverage_text(g)+'）' for g in comparisons)+'。各组约定实测已齐，模型决定停止新增试验；各组结果独立。'
